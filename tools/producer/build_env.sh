VIVID_DIRECT_RUN_DXCOMPILER_LIBRARY="${VIVID_DIRECT_RUN_DXCOMPILER_LIBRARY:-${VIVID_DIRECT_RUN_SCENE_BUILD_DIR}/wallpaper-scene-renderer/dxc-stage/lib/${VIVID_DXCOMPILER_LIBRARY_NAME}}"
# The web backend's out/ directory collocates the worker with the complete CEF
# runtime and the helper executable.
VIVID_DIRECT_RUN_WEB_OUT_DIR="${VIVID_DIRECT_RUN_WEB_OUT_DIR:-${VIVID_DIRECT_RUN_WEB_BUILD_DIR}/worker-out}"

# CEF binary distribution: the archive lives under packaging/flatpak/sources.
# Its upstream filename includes both the exact CEF revision and target
# platform, which prevents an archive downloaded for one architecture from
# being reused by another architecture's build.
VIVID_CEF_ARCHIVE="${VIVID_CEF_ARCHIVE:-${VIVID_PRODUCER_ROOT_DIR}/packaging/flatpak/sources/${VIVID_CEF_ARCHIVE_BASENAME}}"
VIVID_DIRECT_RUN_CEF_DIR="${VIVID_DIRECT_RUN_CEF_DIR:-${VIVID_DIRECT_RUN_BUILD_DIR}/cef}"

VIVID_FLATPAK_MANIFEST="${VIVID_FLATPAK_MANIFEST:-${VIVID_PRODUCER_ROOT_DIR}/packaging/flatpak/io.github.ayasa520.Vivid.yml}"
VIVID_FLATPAK_SOURCES_DIR="${VIVID_FLATPAK_SOURCES_DIR:-${VIVID_PRODUCER_ROOT_DIR}/packaging/flatpak/sources}"
VIVID_FLATPAK_GENERATED_MANIFEST="${VIVID_FLATPAK_GENERATED_MANIFEST:-${VIVID_BUILD_ROOT}/flatpak-manifest/${VIVID_PRODUCER_APP_ID}.yml}"
VIVID_FLATPAK_SOURCE_LOCK="${VIVID_FLATPAK_SOURCE_LOCK:-${VIVID_BUILD_ROOT}/flatpak-manifest/${VIVID_PRODUCER_APP_ID}.source.env}"
VIVID_FLATPAK_GIT_URL="${VIVID_FLATPAK_GIT_URL:-https://github.com/ayasa520/Vivid.git}"
VIVID_FLATPAK_GIT_BRANCH="${VIVID_FLATPAK_GIT_BRANCH:-main}"
