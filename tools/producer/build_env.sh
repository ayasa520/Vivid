VIVID_DIRECT_RUN_SCENE_MANIFEST="${VIVID_DIRECT_RUN_SCENE_MANIFEST:-${VIVID_DIRECT_RUN_RENDERER_ROOT}/${VIVID_SCENE_MANIFEST_NAME}}"
VIVID_DIRECT_RUN_VIDEO_MANIFEST="${VIVID_DIRECT_RUN_VIDEO_MANIFEST:-${VIVID_DIRECT_RUN_RENDERER_ROOT}/${VIVID_VIDEO_MANIFEST_NAME}}"
