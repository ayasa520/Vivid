VIVID_SCENE_SOURCE_DIR="${VIVID_SCENE_SOURCE_DIR:-${VIVID_PRODUCER_RENDERERS_DIR}/scene}"
VIVID_VIDEO_SOURCE_DIR="${VIVID_VIDEO_SOURCE_DIR:-${VIVID_PRODUCER_RENDERERS_DIR}/video}"
VIVID_WEB_SOURCE_DIR="${VIVID_WEB_SOURCE_DIR:-${VIVID_PRODUCER_RENDERERS_DIR}/web}"
VIVID_WEBUI_SOURCE_DIR="${VIVID_WEBUI_SOURCE_DIR:-${VIVID_PRODUCER_SRC_DIR}/webui}"
VIVID_GBM_USAGE_SHIM_SOURCE="${VIVID_GBM_USAGE_SHIM_SOURCE:-${VIVID_WEB_SOURCE_DIR}/vivid_web_gbm_usage_shim.c}"

VIVID_SCENE_TARGET="${VIVID_SCENE_TARGET:-vivid-scene-renderer}"
VIVID_VIDEO_TARGET="${VIVID_VIDEO_TARGET:-vivid-video-renderer}"
VIVID_WEB_TARGET="${VIVID_WEB_TARGET:-vivid-web-renderer}"
VIVID_WEB_HELPER_TARGET="${VIVID_WEB_HELPER_TARGET:-vivid-web-helper}"
VIVID_SCENE_EXECUTABLE_NAME="${VIVID_SCENE_EXECUTABLE_NAME:-vivid-scene-renderer}"
VIVID_VIDEO_EXECUTABLE_NAME="${VIVID_VIDEO_EXECUTABLE_NAME:-vivid-video-renderer}"
VIVID_WEB_EXECUTABLE_NAME="${VIVID_WEB_EXECUTABLE_NAME:-vivid-web-renderer}"
VIVID_SCENE_MANIFEST_NAME="${VIVID_SCENE_MANIFEST_NAME:-vivid-scene.renderer.json}"
