VIVID_DXCOMPILER_LIBRARY_NAME="${VIVID_DXCOMPILER_LIBRARY_NAME:-libdxcompiler.so}"
VIVID_CMAKE_BUILD_TYPE="${VIVID_CMAKE_BUILD_TYPE:-RelWithDebInfo}"

VIVID_RUNTIME_DIR="${VIVID_RUNTIME_DIR:-${XDG_RUNTIME_DIR:-/tmp}}"
VIVID_DEFAULT_DISPLAY_SOCKET="${VIVID_DEFAULT_DISPLAY_SOCKET:-${VIVID_RUNTIME_DIR}/vivid/display-v1.sock}"
VIVID_PRODUCER_APP_ID="${VIVID_PRODUCER_APP_ID:-io.github.ayasa520.Vivid}"
VIVID_PRODUCER_COMMAND_NAME="${VIVID_PRODUCER_COMMAND_NAME:-vivid-producer}"
VIVID_PRODUCER_LAUNCHER_NAME="${VIVID_PRODUCER_LAUNCHER_NAME:-vivid}"
VIVID_FLATPAK_APP_VERSION="${VIVID_FLATPAK_APP_VERSION:-1.0.0}"
VIVID_FLATPAK_RELEASE_DATE="${VIVID_FLATPAK_RELEASE_DATE:-2026-06-18}"
VIVID_DIRECT_RUN_CONFIG_DIR="${VIVID_DIRECT_RUN_CONFIG_DIR:-${HOME:-/tmp}/.var/app/${VIVID_PRODUCER_APP_ID}/config/vivid-producer}"
VIVID_DIRECT_RUN_CONFIG_FILE="${VIVID_DIRECT_RUN_CONFIG_FILE:-${VIVID_DIRECT_RUN_CONFIG_DIR}/config-v1.json}"

VIVID_DIRECT_RUN_BUILD_DIR="${VIVID_DIRECT_RUN_BUILD_DIR:-${VIVID_BUILD_ROOT}/direct-run}"
VIVID_DIRECT_RUN_DAEMON_BUILD_DIR="${VIVID_DIRECT_RUN_DAEMON_BUILD_DIR:-${VIVID_DIRECT_RUN_BUILD_DIR}/daemon-build}"
