VIVID_DIRECT_RUN_WEB_DIR="${VIVID_DIRECT_RUN_WEB_DIR:-${VIVID_DIRECT_RUN_RENDERER_ROOT}/web}"
VIVID_DIRECT_RUN_SCENE_EXECUTABLE="${VIVID_DIRECT_RUN_SCENE_EXECUTABLE:-${VIVID_DIRECT_RUN_SCENE_DIR}/${VIVID_SCENE_EXECUTABLE_NAME}}"
