#!/bin/sh

# Central path configuration for producer build and run scripts.
# Keep directory defaults in one place so local, direct-run, and Flatpak builds
# can be relocated with environment variables instead of editing script bodies.

: "${ROOT_DIR:?ROOT_DIR must be set before sourcing tools/producer/build_env.sh}"

VIVID_PRODUCER_ROOT_DIR="${VIVID_PRODUCER_ROOT_DIR:-${ROOT_DIR}}"
