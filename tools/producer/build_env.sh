VIVID_FLATPAK_BUNDLE_BRANCH="${VIVID_FLATPAK_BUNDLE_BRANCH:-master}"
VIVID_FLATPAK_BUNDLE="${VIVID_FLATPAK_BUNDLE:-${VIVID_BUILD_ROOT}/${VIVID_PRODUCER_APP_ID}-${VIVID_FLATPAK_APP_VERSION}-${VIVID_BUILD_ARCH}.flatpak}"
VIVID_FLATPAK_STATE_DIR="${VIVID_FLATPAK_STATE_DIR:-${VIVID_BUILD_ROOT}/flatpak-builder-state}"
VIVID_FLATPAK_NATIVE_CACHE_DIR="${VIVID_FLATPAK_NATIVE_CACHE_DIR:-${VIVID_BUILD_ROOT}/flatpak-native-cache}"
VIVID_FLATPAK_NATIVE_BUILD_ROOT="${VIVID_FLATPAK_NATIVE_BUILD_ROOT:-${VIVID_FLATPAK_NATIVE_CACHE_DIR}/native-build}"
VIVID_FLATPAK_RUN_DIR="${VIVID_FLATPAK_RUN_DIR:-${VIVID_BUILD_ROOT}/flatpak-run/vivid-producer}"
VIVID_FLATPAK_RENDERER_BUILD_ROOT="${VIVID_FLATPAK_RENDERER_BUILD_ROOT:-${VIVID_BUILD_ROOT}/flatpak-renderer-build}"
VIVID_FLATPAK_DAEMON_BUILD_DIR="${VIVID_FLATPAK_DAEMON_BUILD_DIR:-${VIVID_FLATPAK_RENDERER_BUILD_ROOT}/daemon}"
VIVID_FLATPAK_SCENE_BUILD_DIR="${VIVID_FLATPAK_SCENE_BUILD_DIR:-${VIVID_FLATPAK_RENDERER_BUILD_ROOT}/scene}"
VIVID_FLATPAK_VIDEO_BUILD_DIR="${VIVID_FLATPAK_VIDEO_BUILD_DIR:-${VIVID_FLATPAK_RENDERER_BUILD_ROOT}/video}"
VIVID_FLATPAK_WEB_BUILD_DIR="${VIVID_FLATPAK_WEB_BUILD_DIR:-${VIVID_FLATPAK_RENDERER_BUILD_ROOT}/web}"
VIVID_FLATPAK_CEF_ROOT="${VIVID_FLATPAK_CEF_ROOT:-${VIVID_PRODUCER_ROOT_DIR}/packaging/flatpak/cef}"
VIVID_FLATPAK_GBM_SHIM_BUILD_DIR="${VIVID_FLATPAK_GBM_SHIM_BUILD_DIR:-${VIVID_FLATPAK_RENDERER_BUILD_ROOT}/gbm-usage-shim}"
VIVID_FLATPAK_GBM_USAGE_SHIM="${VIVID_FLATPAK_GBM_USAGE_SHIM:-${VIVID_FLATPAK_GBM_SHIM_BUILD_DIR}/libvivid-gbm-usage-shim.so}"
VIVID_FLATPAK_SCENE_EXECUTABLE="${VIVID_FLATPAK_SCENE_EXECUTABLE:-${VIVID_FLATPAK_SCENE_BUILD_DIR}/out/${VIVID_SCENE_EXECUTABLE_NAME}}"
VIVID_FLATPAK_VIDEO_EXECUTABLE="${VIVID_FLATPAK_VIDEO_EXECUTABLE:-${VIVID_FLATPAK_VIDEO_BUILD_DIR}/out/${VIVID_VIDEO_EXECUTABLE_NAME}}"
VIVID_FLATPAK_WEB_OUT_DIR="${VIVID_FLATPAK_WEB_OUT_DIR:-${VIVID_FLATPAK_WEB_BUILD_DIR}/worker-out}"
VIVID_FLATPAK_DXCOMPILER_LIBRARY="${VIVID_FLATPAK_DXCOMPILER_LIBRARY:-${VIVID_FLATPAK_SCENE_BUILD_DIR}/wallpaper-scene-renderer/dxc-stage/lib/${VIVID_DXCOMPILER_LIBRARY_NAME}}"

VIVID_FLATPAK_RUN_CONFIG_DIR="${VIVID_FLATPAK_RUN_CONFIG_DIR:-${VIVID_FLATPAK_RUN_DIR}/config}"
VIVID_FLATPAK_RUN_CACHE_DIR="${VIVID_FLATPAK_RUN_CACHE_DIR:-${VIVID_FLATPAK_RUN_DIR}/cache}"
VIVID_FLATPAK_RUN_DATA_DIR="${VIVID_FLATPAK_RUN_DATA_DIR:-${VIVID_FLATPAK_RUN_DIR}/data}"
VIVID_FLATPAK_RUN_STATE_DIR="${VIVID_FLATPAK_RUN_STATE_DIR:-${VIVID_FLATPAK_RUN_DIR}/state}"
VIVID_FLATPAK_CONFIG_MOUNT="${VIVID_FLATPAK_CONFIG_MOUNT:-/run/vivid-producer-config}"
VIVID_FLATPAK_CACHE_MOUNT="${VIVID_FLATPAK_CACHE_MOUNT:-/run/vivid-producer-cache}"
VIVID_FLATPAK_DATA_MOUNT="${VIVID_FLATPAK_DATA_MOUNT:-/run/vivid-producer-data}"
