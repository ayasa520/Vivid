VIVID_DIRECT_RUN_VIDEO_BUILD_DIR="${VIVID_DIRECT_RUN_VIDEO_BUILD_DIR:-${VIVID_DIRECT_RUN_BUILD_DIR}/video-build}"
VIVID_DIRECT_RUN_WEB_BUILD_DIR="${VIVID_DIRECT_RUN_WEB_BUILD_DIR:-${VIVID_DIRECT_RUN_BUILD_DIR}/web-build}"
VIVID_DIRECT_RUN_PRODUCER_BIN="${VIVID_DIRECT_RUN_PRODUCER_BIN:-${VIVID_DIRECT_RUN_BUILD_DIR}/vivid-producer-dev}"
VIVID_DIRECT_RUN_GBM_SHIM_BUILD_DIR="${VIVID_DIRECT_RUN_GBM_SHIM_BUILD_DIR:-${VIVID_DIRECT_RUN_BUILD_DIR}/gbm-usage-shim}"
VIVID_DIRECT_RUN_GBM_USAGE_SHIM="${VIVID_DIRECT_RUN_GBM_USAGE_SHIM:-${VIVID_DIRECT_RUN_GBM_SHIM_BUILD_DIR}/libvivid-gbm-usage-shim.so}"
VIVID_DIRECT_RUN_RENDERER_ROOT="${VIVID_DIRECT_RUN_RENDERER_ROOT:-${VIVID_DIRECT_RUN_BUILD_DIR}/renderer-registry-v1}"
