case "${VIVID_BUILD_ARCH}" in
    x86_64)
        VIVID_CEF_PLATFORM=linux64
        VIVID_CEF_ARCHIVE_SHA1="${VIVID_CEF_LINUX64_SHA1}"
        ;;
    aarch64)
        VIVID_CEF_PLATFORM=linuxarm64
        VIVID_CEF_ARCHIVE_SHA1="${VIVID_CEF_LINUXARM64_SHA1}"
        ;;
esac

VIVID_CEF_ARCHIVE_BASENAME="cef_binary_${VIVID_CEF_VERSION}_${VIVID_CEF_PLATFORM}_minimal.tar.bz2"
VIVID_CEF_ARCHIVE_URL="${VIVID_CEF_DOWNLOAD_BASE_URL}/${VIVID_CEF_ARCHIVE_BASENAME}"

VIVID_PRODUCER_SRC_DIR="${VIVID_PRODUCER_SRC_DIR:-${VIVID_PRODUCER_ROOT_DIR}/src}"
